// read directory structure from JSON generated by src/dir_gen.py
async function loadDirectoryStructure() {
    const response = await fetch("generated/directory_structure.json");
    const structure = await response.json();
    return processDirectory(structure);
}

function processDirectory(directory, parent=undefined) {
    let dir_obj = new Folder(directory.name, parent);
    for (const item of directory.children) {
        if (item.type === "directory") {
            dir_obj.addFolder(processDirectory(item, dir_obj));
        } else if (item.type === "file") {
            let file_obj = new File(item.name, item.contents, true);
            dir_obj.addFile(file_obj);
        } else if(item.type === "served_file") {
            let file_obj = new File(item.name, item.full_path, false);
            dir_obj.addFile(file_obj)
        }
        else{
            throw "Unrecognized file type: " + item.type
        }
        
    }
    return dir_obj;
}

