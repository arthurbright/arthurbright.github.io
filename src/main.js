//get a folder from its path
function getFolder(ostr, getf=false){
    let str = ostr;
    // if(str.startsWith("~") || str.startsWith("\\")){
    //     str = home_folder + str;
    // }
    if(str.startsWith(home_folder)){
        // do nothing
    }
    else{
        str = curFolder.path + "/" + str;
    }
    let arr = str.split(/\/|\\/).filter((x) => {return x != ""});
    
    let cur = root;
    for(let i = 1; i < arr.length; i ++){
        if(i == arr.length - 1 && getf){
            for(let file of cur.files){
                if(file.name == arr[i]){
                    return file;
                }
            }
            return undefined;
        }


        if(arr[i] == ".") continue;
        if(arr[i] == ".."){
            if(cur.parent){
                cur = cur.parent;
                continue;
            }
            else{
                return undefined;
            }
        }

        let found = false;
        for(let sub of cur.subfolders){
            if(sub.name == arr[i]){
                found = true;
                cur = sub;
                break;
            }
        }
        if(found) continue;
        return undefined;
    }
    return cur;
}

// get a file from its path
function getFile(ostr){
    return getFolder(ostr, true);
}


